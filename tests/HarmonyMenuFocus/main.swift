import Foundation
func check(_ result: Bool, _ label: String) { if !result { fatalError(label) } }
var intent = HarmonyMenuFocusIntent()
intent.begin(token: "word", ownerPID: 234, now: 10)
check(!intent.consume(token: "word", ownerPID: 114, now: 10.15), "Finder must not use Word intent")
check(intent.consume(token: "word", ownerPID: 234, now: 10.2), "wrong owner does not consume valid reply")
check(!intent.consume(token: "word", ownerPID: 234, now: 10.3), "one shot")
intent.begin(token: "old", ownerPID: 234, now: 20)
intent.begin(token: "new", ownerPID: 234, now: 20.1)
check(!intent.consume(token: "old", ownerPID: 234, now: 20.2), "superseded")
check(intent.consume(token: "new", ownerPID: 234, now: 20.3), "new selection")
intent.begin(token: "exit", ownerPID: 234, now: 30)
intent.cancel()
check(!intent.consume(token: "exit", ownerPID: 234, now: 30.1), "session cancellation")
intent.begin(token: "expired", ownerPID: 234, now: 40)
check(!intent.consume(token: "expired", ownerPID: 234, now: 42.01), "deadline")
intent.begin(token: "invalid", ownerPID: 0, now: 50)
check(!intent.consume(token: "invalid", ownerPID: 0, now: 50.1), "invalid owner")
print("PASS: menu focus owner, one-shot, supersession, cancellation, deadline")
