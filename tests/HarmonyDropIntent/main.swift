import Foundation
func check(_ result: Bool, _ label: String) { precondition(result, label) }
var intent = HarmonyDropIntent()
let epoch = UUID()
check(!intent.consume(sequence: 1, epoch: epoch, destinationValid: true), "release without enter")
intent.enter(sequence: 1, epoch: epoch)
intent.cancel()
check(!intent.consume(sequence: 1, epoch: epoch, destinationValid: true), "hover then leave then release")
intent.enter(sequence: 2, epoch: epoch)
check(!intent.consume(sequence: 2, epoch: epoch, destinationValid: false), "release outside destination even without exit callback")
intent.enter(sequence: 3, epoch: epoch)
check(!intent.consume(sequence: 3, epoch: UUID(), destinationValid: true), "Harmony exit/reentry")
intent.enter(sequence: 4, epoch: epoch)
check(!intent.consume(sequence: 5, epoch: epoch, destinationValid: true), "different drag")
intent.enter(sequence: 6, epoch: epoch)
check(intent.accepts(sequence: 6, epoch: epoch, destinationValid: true), "prepare is nonconsuming")
check(intent.consume(sequence: 6, epoch: epoch, destinationValid: true), "intentional drop")
check(!intent.consume(sequence: 6, epoch: epoch, destinationValid: true), "no duplicate imports")
intent.enter(sequence: 7, epoch: epoch); intent.cancel(); intent.enter(sequence: 7, epoch: epoch)
check(intent.consume(sequence: 7, epoch: epoch, destinationValid: true), "leave then deliberately reenter")
print("PASS: drop exit, release outside, session, sequence, preparation, single commit and reentry")
